# item_icon_table.py: writes Assets/Scripts/Runtime/Core/Content/ItemIconTable.cs from Reference/research/item_icons.json (the
# shop icons' places in the original's atlases, ItemIconBuilder's input), for the converter's DerivedImages.ItemIcons, which
# can't read the json (plain C#, no JSON reader). Run it after changing the json.
#   python3 Reference/tools/player_assets/item_icon_table.py
import json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
d = json.load(open(os.path.join(ROOT, "Reference", "research", "item_icons.json")))["entries"]
frames = {e["imageId"]: e for e in d if e["kind"] == "ui"}
lines = []
for e in d:
    if e["kind"] not in ("item", "ship") or e.get("index", -1) < 0 or not e.get("rect"): continue
    f = frames.get(e.get("frameImageId"))
    fa, fr = (f["atlas"][:-4], f["rect"]) if f else ("", [0, 0, 0, 0])
    r = e["rect"]
    lines.append(f'            ("{e["kind"]}", {e["index"]}, "{e["atlas"][:-4]}", {r[0]}, {r[1]}, {r[2]}, {r[3]}, "{fa}", {fr[0]}, {fr[1]}, {fr[2]}, {fr[3]}),')
src = '''// ItemIconTable.cs (generated by Reference/tools/player_assets/item_icon_table.py from Reference/research/item_icons.json:
// keep it in step with that file). The shop icons' places in the original's atlases (ItemIconBuilder's input), for
// DerivedImages.ItemIcons: kind, index, icon atlas + rect (top-left x, y, w, h), its frame's atlas + rect.

namespace GoF2Remake.Data
{
#if UNITY_5_3_OR_NEWER
    [Unity.Scripting.LifecycleManagement.NoAutoStaticsCleanup]   // (only constant tables: nothing to reset)
#endif
    public static class ItemIconTable
    {
        public static readonly (string kind, int index, string atlas, int x, int y, int w, int h, string frameAtlas, int fx, int fy, int fw, int fh)[] Icons =
        {
''' + "\n".join(lines) + '''
        };
    }
}
'''
out = os.path.join(ROOT, "Assets", "Scripts", "Runtime", "Core", "Content", "ItemIconTable.cs")
open(out, "w").write(src)
print(len(lines), "icons ->", out)
