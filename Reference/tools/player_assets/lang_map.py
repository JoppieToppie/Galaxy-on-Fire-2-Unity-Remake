# lang_map.py: writes Assets/Scripts/Runtime/Core/Content/LangMaps.cs, the string-ID map of an edition whose text tables
# are laid out differently from the Android copy's (the remake's IDs: a ship's name is 913 + its index...). The macOS Full
# HD app's tables have 3,385 strings to Android's 3,401: the same strings in the same order with a few added, dropped or
# reworded (docs/notes/player-assets.md "The macOS copy"). Aligns the two English tables (line endings normalised; equal
# runs, then reworded strings paired in order by similarity) and stores the runs (android id, edition id, length); the
# converter (OriginalConverter) puts an edition's strings at the Android ids, the unmatched ids left empty (the packs'
# text overlay fills them). Run after converting both copies:
#   python3 Reference/tools/player_assets/lang_map.py --android <cache>/Localization/text_en.json \
#       --edition macos=<cache>/Localization/text_en.json
import argparse, difflib, json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))


def norm(s): return s.replace("\r\n", "\n").strip()


def align(a, b):
    """(android id, edition id) pairs, increasing in both."""
    na, nb = [norm(s) for s in a], [norm(s) for s in b]
    pairs = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, na, nb, autojunk=False).get_opcodes():
        if tag == "equal":
            pairs += [(i1 + k, j1 + k) for k in range(i2 - i1)]
        elif tag == "replace":
            # reworded or shifted: pair in order where the strings are alike (the rest has no counterpart)
            j = j1
            for i in range(i1, i2):
                best, bj = 0.0, None
                for jj in range(j, j2):
                    r = difflib.SequenceMatcher(None, na[i], nb[jj]).ratio()
                    if r > best: best, bj = r, jj
                if bj is not None and best >= 0.5:
                    pairs.append((i, bj)); j = bj + 1
    return pairs


def runs(pairs):
    out = []
    for ia, ib in pairs:
        if out and out[-1][0] + out[-1][2] == ia and out[-1][1] + out[-1][2] == ib: out[-1][2] += 1
        else: out.append([ia, ib, 1])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--android", required=True)
    ap.add_argument("--edition", action="append", required=True, help="name=text_en.json")
    a = ap.parse_args()
    android = json.load(open(a.android, encoding="utf-8"))
    entries = []
    for e in a.edition:
        name, path = e.split("=", 1)
        ed = json.load(open(path, encoding="utf-8"))
        pairs = align(android, ed)
        r = runs(pairs)
        print(f"{name}: {len(ed)} strings, {len(pairs)} at Android ids ({len(android) - len(pairs)} Android ids unmatched), {len(r)} runs")
        entries.append(f'            ["{name}"] = ({len(ed)}, new[] {{ ' + ", ".join(f"{x}, {y}, {n}" for x, y, n in r) + " }),")
    src = f'''// LangMaps.cs (generated by Reference/tools/player_assets/lang_map.py: run it again rather than editing). The string-ID
// map of each edition whose text tables are laid out differently from the Android copy's, whose ids the remake uses:
// edition -> (its table's string count, runs of [Android id, edition id, length]). The converter puts such an edition's
// strings at the Android ids (OriginalConverter); ids without a counterpart stay empty.

using System.Collections.Generic;

namespace GoF2Remake.Data
{{
#if UNITY_5_3_OR_NEWER
    [Unity.Scripting.LifecycleManagement.NoAutoStaticsCleanup]   // (only constant tables: nothing to reset)
#endif
    public static class LangMaps
    {{
        /// <summary>The Android tables' string count (the remake's ids 0 .. AndroidCount - 1).</summary>
        public const int AndroidCount = {len(android)};

        public static readonly Dictionary<string, (int count, int[] runs)> Editions = new Dictionary<string, (int, int[])>
        {{
{chr(10).join(entries)}
        }};

        /// <summary>An edition's strings at the Android ids (null when the edition needs no map or the table isn't its).</summary>
        public static List<string> ToAndroidIds(string edition, List<string> strings)
        {{
            if (edition == null || !Editions.TryGetValue(edition, out var m) || strings.Count != m.count) return null;
            var o = new List<string>(AndroidCount);
            for (int i = 0; i < AndroidCount; i++) o.Add("");
            for (int r = 0; r + 2 < m.runs.Length; r += 3)
                for (int k = 0; k < m.runs[r + 2]; k++) o[m.runs[r] + k] = strings[m.runs[r + 1] + k];
            return o;
        }}
    }}
}}
'''
    out = os.path.join(ROOT, "Assets", "Scripts", "Runtime", "Core", "Content", "LangMaps.cs")
    open(out, "w", encoding="utf-8").write(src)
    print("->", out)


if __name__ == "__main__":
    main()
